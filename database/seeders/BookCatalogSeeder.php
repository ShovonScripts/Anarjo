        ];
        $phala = ['য' => 'y', 'র' => 'r', 'ল' => 'l', 'ব' => 'b', 'ম' => 'm', 'ন' => 'n'];
        $digits = ['০' => '0', '১' => '1', '২' => '2', '৩' => '3', '৪' => '4', '৫' => '5', '৬' => '6', '৭' => '7', '৮' => '8', '৯' => '9'];
        $others = ['ং' => 'ng', 'ঃ' => 'h', 'ঁ' => 'n', '&' => 'and', '@' => 'at'];

        $chars = preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY);
        $count = count($chars);
        $out = '';
        $i = 0;

        while ($i < $count) {
            $ch = $chars[$i];

            if ($ch === ' ' || preg_match('/[A-Za-z0-9]/u', $ch)) {
                $out .= $ch;
                $i++;

                continue;
            }

            if ($ch === '্') {
                $i++;

                continue;
            }

            if (isset($consonants[$ch])) {
                $cval = $consonants[$ch];

                if (($chars[$i + 1] ?? null) === '্') {
                    $out .= $cval;
                    $i += 2;
                    if (isset($chars[$i]) && isset($consonants[$chars[$i]])) {
                        $out .= $phala[$chars[$i]] ?? $consonants[$chars[$i]];
                        $i++;
                        if (isset($chars[$i]) && isset($vowelSigns[$chars[$i]])) {
                            $out .= $vowelSigns[$chars[$i]];
                            $i++;
                        }
                    }

                    continue;
                }

                if (isset($chars[$i + 1]) && isset($vowelSigns[$chars[$i + 1]])) {
                    $out .= $cval.$vowelSigns[$chars[$i + 1]];
                    $i += 2;

                    continue;
                }

                $next = $chars[$i + 1] ?? null;
                if ($next === null || $next === ' ' || (! isset($vowelSigns[$next]) && ! isset($consonants[$next]))) {
                    $out .= $cval;
                } else {
                    $out .= $cval.'a';
                }
                $i++;

                continue;
            }

            if (isset($vowels[$ch])) {
                $out .= $vowels[$ch];
                $i++;

                continue;
            }

            $out .= $digits[$ch] ?? $others[$ch] ?? '';
            $i++;
        }

        return $out;
    }

    private function detectLanguage(string $title): string
    {
        $hasLatin = preg_match('/[A-Za-z]/u', $title) === 1;
        $hasBengali = preg_match('/\p{Bengali}/u', $title) === 1;

        return $hasLatin && ! $hasBengali ? 'English' : 'Bengali';
    }

    private function resolveAuthor(?string $name): ?int
    {
        if (! $name) {
            return null;
        }

        $key = $this->normalizeName($name);

        if (isset($this->authors[$key])) {
            return $this->authors[$key];
        }

        $author = Author::firstOrCreate(
            ['slug' => $this->uniqueAuthorSlug($name)],
            [
                'name' => $name,
                'status' => 'active',
            ]
        );

        return $this->authors[$key] = $author->id;
    }

    protected array $authors = [];

    protected array $usedAuthorSlugs = [];

    private function uniqueAuthorSlug(string $name): string
    {
        $base = $this->slugify($name) ?: 'author';
        $slug = $base;

        if (isset($this->usedAuthorSlugs[$slug]) || Author::where('slug', $slug)->exists()) {
            $i = 2;
            while (isset($this->usedAuthorSlugs["{$base}-{$i}"]) || Author::where('slug', "{$base}-{$i}")->exists()) {
                $i++;
            }
            $slug = "{$base}-{$i}";
        }

        $this->usedAuthorSlugs[$slug] = true;

        return $slug;
    }

    private function normalizeName(string $name): string
    {
        $name = str_replace(['ী', 'ূ', 'ঈ', 'ঊ'], ['ি', 'ু', 'ই', 'উ'], $name);
        $name = str_replace(['ণ', 'ষ', 'শ'], ['ন', 'স', 'স'], $name);
        $name = str_replace([
            'ডা. ', 'ডাঃ ', 'ড. ', 'ডঃ ', 'প্রফেসর ', 'অধ্যাপক ', 'অধ্যক্ষ ', 'মোঃ ', 'মো. ', 'মু. ',
            'কে. ', 'কি. ', 'শ্রী ', '(অব.) ', '(অব)', '(রহঃ) ', '(রহঃ)', '(রহ.) ', '(রহ.)', 'বীর মুক্তিযোদ্ধা ',
            'সম্পাদনা: ', 'অনুবাদ: ', 'সংকলন: ', 'রূপান্তর: ', 'মূল: ', 'রচনা: ',
        ], '', $name);
        $name = preg_replace('/[^\p{Bengali}A-Za-z]/u', '', $name);

        return $name;
    }
