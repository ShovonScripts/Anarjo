    public function run(): void
    {
        foreach ($this->catalog as $cat) {
            $category = Category::firstOrCreate(
                ['slug' => $cat['slug']],
                ['name' => $cat['name']]
            );

            foreach ($cat['books'] as $item) {
                $authorId = $this->resolveAuthor($item['author'] ?? null);

                $book = Book::updateOrCreate(
                    ['title' => $item['title'], 'author_id' => $authorId],
                    [
                        'slug' => $this->uniqueSlug($item['title']),
                        'price' => $item['price'],
                        'sale_price' => null,
                        'stock' => rand(5, 30),
                        'language' => $this->detectLanguage($item['title']),
                        'excerpt' => $item['credit'] ?? null,
                        'status' => 'published',
                    ]
                );

                $book->categories()->syncWithoutDetaching([$category->id]);
            }
        }

        $this->command?->info('Book catalog seeded.');
    }

    protected array $usedSlugs = [];

    private function uniqueSlug(string $title): string
    {
        $base = $this->slugify($title) ?: 'book';
        $slug = $base;

        if (isset($this->usedSlugs[$slug]) || Book::where('slug', $slug)->exists()) {
            $i = 2;
            while (isset($this->usedSlugs["{$base}-{$i}"]) || Book::where('slug', "{$base}-{$i}")->exists()) {
                $i++;
            }
            $slug = "{$base}-{$i}";
        }

        $this->usedSlugs[$slug] = true;

        return $slug;
    }

    private function slugify(string $text): string
    {
        $latin = $this->transliterate($text);

        return Str::slug($latin) ?: Str::slug($text);
    }

